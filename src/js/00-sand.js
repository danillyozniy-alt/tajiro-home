/* ============================================================
   ПЕСОК · общий материал

   Песок живёт на странице ровно в одном месте — на первом экране, полем,
   которое расступается под курсором. Шум, палитра и способ выбрать тон по
   величине вынесены сюда, потому что это язык материала, а не настройки
   одного экрана.

   Пробовали разложить его ещё в двух местах: тихим горизонтом под карточками
   доверия и грунтом под последней кнопкой. Отказались — материал, повторённый
   трижды, перестаёт быть приёмом и становится обоями.

   Приём взят с первого экрана craft.wild.as.

   ПРО СКОРОСТЬ

   На первом экране закон рябы считается для сорока тысяч ячеек в кадр, и
   почти всё время уходило на тригонометрию: восемьдесят семь тысяч синусов на
   решётку плюс двадцать семь тысяч на шум — одиннадцать миллисекунд из
   шестнадцати с половиной. Поэтому здесь синус берётся из таблицы, а хеш
   считается целыми числами, а не через синус. Кадр подешевел с 11 до 4.4 мс,
   наибольшая ошибка синуса — две тысячных, при том что тона палитры шагают
   через 0.14. На глаз разницы нет никакой.
   ============================================================ */
window.TAJIRO_SAND = (function () {
  var SEED = 1.7320508;             /* постоянное: поле не должно прыгать при пересборке */

  /* --- быстрый синус ------------------------------------------------------
     Таблица на 4096 отсчётов и выборка ближайшего. Без промежуточного
     сглаживания: ошибка и так меньше, чем шаг палитры. -------------------- */
  var N = 4096, MASK = N - 1, K = N / (Math.PI * 2), Q = N / 4;
  var TAB = new Float32Array(N);
  for (var i = 0; i < N; i++) TAB[i] = Math.sin(i / N * Math.PI * 2);

  function sin(x) { return TAB[((x * K + 0.5) | 0) & MASK]; }
  function cos(x) { return TAB[((x * K + Q + 0.5) | 0) & MASK]; }

  /* --- хеш ----------------------------------------------------------------
     Целочисленный, а не через синус: одна и та же пара координат всегда даёт
     одно и то же число, и не надо ничего хранить. Прежний вариант считал
     Math.sin и стоил два миллисекунда на кадр только на решётке. ---------- */
  function hash(x, y) {
    var h = (Math.imul((x * 1024) | 0, 374761393) + Math.imul((y * 1024) | 0, 668265263)) | 0;
    h = Math.imul(h ^ (h >>> 13), 1274126177) | 0;
    return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
  }

  /* --- шумовое поле -------------------------------------------------------
     Сумма нескольких синусов со сдвигом по времени. Именно она заставляет
     песок течь, а не мерцать на месте. ------------------------------------- */
  function noise(nx, ny, tt) {
    var s = SEED;
    nx += sin(ny * 5 + tt * 0.5 + s) * 0.05;
    ny += cos(nx * 5 - tt * 0.4) * 0.05;
    var v = sin(nx * 5.6 + s * 1.3 + tt * 0.3) * cos(ny * 4.7 - s * 0.7 + tt * 0.22)
          + sin((nx * 1.4 + ny * 1.7) * 4.1 - s + tt * 0.16)
          + sin(ny * 9 + s * 2.1 + nx * 3) * 0.5
          + sin(nx * 13 - s * 1.7) * 0.28;
    return 0.5 + 0.5 * (v / 2.55);
  }

  function smooth(a, b, v) {
    var q = (v - a) / (b - a);
    q = q < 0 ? 0 : q > 1 ? 1 : q;
    return q * q * (3 - 2 * q);
  }

  /* --- палитра ------------------------------------------------------------
     У крупинки нет своего цвета, есть только величина, а тон берётся по ней.
     Приём с образца — там ровно так же цвет задаётся не принадлежностью, а
     «температурой». Тон здесь углубляется, а не меняет род: это песок разной
     плотности, а не четыре разные краски. --------------------------------- */
  var RAMP = [
    [0.30, [224, 213, 193]],
    [0.44, [207, 188, 152]],
    [0.58, [185, 152,  99]],
    [0.72, [154, 112,  59]]
  ];

  /* Та же лестница для тёмного грунта: на чёрном песок не темнеет, а
     светится, поэтому полосы идут снизу вверх по светлоте. Финальный призыв
     стоит на тёмном, и без этой пары песок был бы там невидим. */
  var RAMP_DARK = [
    [0.30, [ 56,  48,  40]],
    [0.44, [ 92,  76,  57]],
    [0.58, [140, 108,  71]],
    [0.72, [198, 156, 102]]
  ];

  function toneOn(v, dark) {
    var R = dark ? RAMP_DARK : RAMP;
    var col = R[0][1];
    if (v >= R[1][0]) col = R[1][1];
    if (v >= R[2][0]) col = R[2][1];
    if (v >= R[3][0]) col = R[3][1];
    return col;
  }

  function tone(v) { return toneOn(v, false); }

  return {
    SEED: SEED, sin: sin, cos: cos, hash: hash, noise: noise, smooth: smooth,
    RAMP: RAMP, RAMP_DARK: RAMP_DARK, tone: tone, toneOn: toneOn
  };
})();
