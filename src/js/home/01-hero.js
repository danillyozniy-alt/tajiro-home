/* ============================================================
   ПЕСОК, КОТОРЫЙ РАССТУПАЕТСЯ

   Конструкция взята с первого экрана craft.wild.as: холст зафиксирован во
   весь экран, лежит фоном всего документа, не ловит мышь и рисует в
   координатах СТРАНИЦЫ — поэтому поле кажется приклеенным к бумаге и уезжает
   вместе с содержимым, хотя сам холст неподвижен. Оттуда же приём насыпания:
   поле не проявляется градиентом, а набирается случайными ячейками.

   А вот курсор здесь работает иначе, чем у них, и это главное отличие.

   У образца курсор ВПРЫСКИВАЕТ ТЕПЛО: ячейки под ним разгораются, и за мышью
   таскается светящийся круг. Так было и здесь — и это оказалось не тем.

   Теперь курсор РАЗДВИГАЕТ ПЕСОК. Крупинки в радиусе отталкиваются от него
   наружу тем сильнее, чем ближе; в самой середине их нет вовсе, а по кромке
   они наезжают друг на друга и образуют уплотнённый вал. Это две строки
   геометрии на отрисовке: ячейка рисуется не там, где лежит, а сдвинутой по
   вектору от курсора.

   Плюс память следа. Без неё песок схлопывается за курсором мгновенно и
   движение читается резиновой плёнкой, а не сыпучим телом. Поэтому пройденное
   помнится в carve[] и затягивается за полторы секунды.

   Текста на холсте нет ни одной буквы: заголовок остаётся настоящим текстом
   в разметке, а поле обтекает боксы, взятые из неё по метке data-sand-clear.
   ============================================================ */
(function () {
  var cv = document.getElementById('hero-sand');
  var hero = document.getElementById('hero');
  if (!cv || !hero || !cv.getContext || !window.TAJIRO_SAND) return;
  var ctx = cv.getContext('2d');
  var reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;

  var BG = [245, 240, 235];

  /* Зерно. Мельче, чем у образца: у них девять пикселей и это читается
     пикселями, нам нужен песок. */
  var CELL = 4;
  var GAP = 1;
  /* Порог и сглаживание впадин вместе решают, насколько поле сплошное.

     При 0.34 и 0.90 оно распадалось на острова: из 276 участков экрана 149
     были пусты почти начисто, а медианная плотность по экрану равнялась нулю.
     Рядом с крупным заголовком это читалось прямо белыми проплешинами.

     Опущенный порог и менее сглаженные впадины поднимают дно, не трогая
     гребней: пустых участков 131 вместо 149, медиана — шесть процентов вместо
     нуля, а узор остаётся тем же. Дальше опускать нельзя: на 0.26 и 0.70 поле
     заливается сплошняком и рябь пропадает вовсе. */
  var CUT = 0.28;
  var DENS = 1.00;
  var LOD = 3;                  /* через сколько ячеек считается закон */
  var INTRO = 1.6;
  var DRIFT = -0.05;            /* ветер: поле медленно идёт слева направо */

  /* Масштаб шума. Меряется он ОДНОЙ шкалой по обеим осям — высотой экрана.
     Пока я брал долю ширины по горизонтали и долю высоты по вертикали, узор
     растягивался ровно во столько раз, во сколько экран шире, чем выше, и его
     впадины превращались в широкие диагональные пробелы. Их и было видно как
     странную пустую полосу посреди песка. */
  var SCALE = 3.6;              /* больше — мельче узор */
  var REF = 720;                /* к какой высоте привязан масштаб узора */

  var CALM = 0.78;              /* насколько сглажены впадины: 1 — как есть */

  /* Рябь. Правильные гребни поперёк ветра — то, чем песок и отличается от
     любого другого шумового поля. Но параллельный марш полос на светлом фоне
     читается тканью, а не дюной, поэтому здесь гребни ГУЛЯЮТ: фаза сильно
     покороблена шумом, а само направление медленно поворачивается. Заодно
     уходит риск муара — период перестаёт совпадать с шагом сетки. */
  var RIP_K = 2.9;              /* частота гребней */
  var RIP_WARP = 6.5;           /* насколько шум коробит фазу */
  var RIP_TURN = 0.045;         /* как быстро поворачивается направление */
  var RIP_RUN = 0.18;           /* как быстро гребни ползут */
  var RIP_MIX = 0.70;           /* доля гребней против мягкой подложки */

  /* Мягкий порог. Раньше ячейка сравнивалась с порогом жёстко, и когда
     величина его переходила — крупинка вспыхивала или гасла НА МЕСТЕ. Замер
     показывал 33 процента смен за секунду: поле мерцало, а не двигалось.

     Пробовал дать крупинке жизнь и снос по ветру — стало хуже: узор ведь и
     так едет, и крупинка поехала СВЕРХ него. Двойное движение размазало
     гребни, ради которых рябь и выбрана.

     Едет пусть узор, а крупинке достаточно не щёлкать. Поэтому у порога она
     не возникает разом, а проступает: подходит гребень — проявляется,
     уходит — тает. Движение гребня само читается волной яркости. */
  var SOFT = 0.20;              /* ширина полосы, в которой крупинка проступает */

  /* Курсор раздвигает песок */
  /* Радиус считается от ПУСТОГО МЕСТА: R * CORE = 33 пиксела, столько же,
     сколько было раньше. Дальше идёт вал, и всё вместе укладывается в 51
     пиксел вместо прежних 104 — след курсора стал вдвое компактнее, зато
     теперь в нём есть что разглядывать. */
  var R = 72;                   /* радиус влияния, css-пиксели */
  /* ПУСТОЕ МЕСТО И ВАЛ ВОКРУГ НЕГО

     Курсор не стирает песок, а сгребает его. Значит вынутое обязано где-то
     лежать, и лежать плотно: вся середина круга — в узком кольце по кромке.

     Ширина кольца — не вкус, а счёт по площади. Если песок из круга радиуса A
     ложится в кольцо от A до A*G, то плотность в кольце растёт в G²/(G²-1)
     раз. При G = 1.55 это ровно 1.7 — вал заметно темнее поля, но не
     превращается в нарисованный обруч.

     Прошлый заход провалился именно здесь: вынутое из круга в 31 пиксель
     раскидывалось на кольцо шириной 73, и прибавка выходила в десять
     процентов. Такого не видно вовсе. */
  var CORE = 0.46;              /* доля радиуса, где песка нет вовсе */
  var GROW = 1.55;              /* до скольких радиусов пустого места ложится вал */
  var HEAL = 0.965;             /* с какой скоростью затягивается след */
  var VREF = 11;                /* скорость, при которой борозда вытянута сполна */

  /* Телефон. Курсора там нет, и песок раздвигает палец — тем же расчётом, что
     мышь. Проходивший здесь раньше порыв ветра убран: он читался волной,
     идущей через экран, а экран должен отзываться на человека, а не жить
     сам по себе. */
  var TOUCH = !(window.matchMedia && matchMedia('(hover: hover) and (pointer: fine)').matches);
  /* Борозду пробовали и отказались. Замысел был такой: на ходу область
     влияния вытягивается вдоль движения, а песок валит вбок от линии, как
     из-под ведомой по песку руки. Всё это время оно не работало — расчёт
     скорости давал NaN, и на экране был ровный круг. Когда ошибку починили и
     борозда наконец появилась, выяснилось, что она хуже: овал тянется и
     назад тоже, и половина его волочится за курсором — читается как
     подтормаживание, хотя кадр укладывается в 4,7 мс из 16,7.

     Единица и ноль возвращают круг. Расчёт вытянутости при этих числах
     вырождается в обычное расстояние, так что и лишней работы нет. */
  var ELONG = 1.0;              /* 1 — область влияния всегда круглая */

  /* Прокрутка. Поле едет вместе с бумагой, но сыпучее тело не может ехать как
     приклеенное: на резком движении оно отстаёт и сдвигается неравномерно.
     Отсюда сдвиг по вертикали, у каждой крупинки свой. */
  var SLAG = 0.55;              /* доля скорости прокрутки, на которую песок отстаёт */
  var SLAG_MAX = 46;            /* дальше отставание не растёт: иначе выйдет смаз */
  var LATERAL = 0;              /* 0 — песок расходится радиально, а не вбок */

  /* Шум, палитра и выбор тона — общие для всех трёх мест, где на странице
     работает песок. Лежат в js/00-sand.js: разойдись они по трём скриптам,
     песок в трёх местах зажил бы тремя разными жизнями. */
  var SAND = window.TAJIRO_SAND;

  var W = 0, H = 0, PW = 0, PH = 0, dpr = 1;
  var cols = 0, rows = 0, step = 0, sq = 0;
  var carve = null, img = null, boxes = [], grid = null;
  var raf = 0, t0 = 0, t = 0, tries = 0;
  var SEED = SAND.SEED;
  var mx = -1e5, my = -1e5, over = false, rad = 0, radT = 0;

  /* Скорость курсора. Из неё растёт вытягивание проплешины: стоящая мышь
     оставляет круглое место, ведомая — борозду вдоль хода. */
  var vx = 0, vy = 0;                 /* сглаженная скорость, устройственные пиксели за кадр */
  var sy0 = 0, svel = 0;              /* положение и сглаженная скорость прокрутки */
  var lx = -1e5, ly = -1e5;           /* где курсор был в прошлом событии */
  var seg = [];                       /* отрезки хода, по ним ставится след */

  var hash = SAND.hash, base = SAND.noise;
  var fsin = SAND.sin, fcos = SAND.cos;


  /* Боксы, которые поле обтекает. Берутся из разметки по метке, а не списком
     в скрипте: добавили строку в первый экран — она сама себя защитила.

     У блочного текста коробка берётся ПОСТРОЧНО, а не одна на весь блок.
     Коробка заголовка — 1145 на 306, а его последняя строка вдвое уже: по
     общей коробке песок вычищался на всю ширину блока, и рядом с короткими
     строками оставались большие пустые поля. Range по содержимому отдаёт по
     прямоугольнику на строку, каждый ровно по ширине набранного.

     Строчным элементам — пилюле, кнопкам, сноске — наоборот нужна коробка
     самого элемента: у них есть рамка и заливка, которые шире текста. */
  function measure() {
    boxes = [];
    [].forEach.call(hero.querySelectorAll('[data-sand-clear]'), function (e) {
      var rs;
      if (getComputedStyle(e).display.indexOf('block') === 0) {
        var rg = document.createRange();
        rg.selectNodeContents(e);
        rs = rg.getClientRects();
      }
      if (!rs || !rs.length) rs = [e.getBoundingClientRect()];
      for (var i = 0; i < rs.length; i++) {
        var r = rs[i];
        if (r.width < 1 || r.height < 1) continue;
        boxes.push([(r.left + scrollX) * dpr, (r.top + scrollY) * dpr,
                    (r.right + scrollX) * dpr, (r.bottom + scrollY) * dpr]);
      }
    });
    var hb = hero.getBoundingClientRect();
    measure.top = (hb.top + scrollY) * dpr;
    measure.bottom = (hb.bottom + scrollY) * dpr;
  }

  function size() {
    W = innerWidth; H = innerHeight;
    if (!W || !H) return false;
    dpr = Math.min(devicePixelRatio || 1, 1.5);
    PW = Math.round(W * dpr); PH = Math.round(H * dpr);
    cv.width = PW; cv.height = PH;

    step = Math.max(3, Math.round(CELL * dpr));
    sq = Math.max(2, step - Math.round(GAP * dpr));
    cols = Math.ceil(PW / step) + 1;
    rows = Math.ceil(PH / step) + 2;

    /* След помнится по экранным ячейкам: он живёт секунду и к бумаге не
       привязан. */
    carve = new Float32Array(cols * rows);

    img = ctx.createImageData(PW, PH);
    var d = img.data;
    for (var p = 0, n = PW * PH; p < n; p++) {
      d[p * 4] = BG[0]; d[p * 4 + 1] = BG[1]; d[p * 4 + 2] = BG[2]; d[p * 4 + 3] = 255;
    }
    measure();
    return true;
  }

  /* Крупинка кладётся по фактическим пикселям, а не по клетке: раздвигание
     смещает её на дробную величину, и привязка к сетке эту дробность съела бы. */
  function grain(d, px, py, col, a) {
    var x0 = px | 0, y0 = py | 0;
    var x1 = x0 + sq, y1 = y0 + sq;
    if (x1 <= 0 || y1 <= 0 || x0 >= PW || y0 >= PH) return;
    if (x0 < 0) x0 = 0; if (y0 < 0) y0 = 0;
    if (x1 > PW) x1 = PW; if (y1 > PH) y1 = PH;

    /* Непрозрачную крупинку пишем напрямую, прочие смешиваем с фоном: на
       рождении и смерти она прозрачна, и переключения не видно. */
    if (a >= 0.985) {
      for (var y = y0; y < y1; y++) {
        var row = y * PW;
        for (var x = x0; x < x1; x++) {
          var i = (row + x) * 4;
          d[i] = col[0]; d[i + 1] = col[1]; d[i + 2] = col[2];
        }
      }
      return;
    }
    var r0c = BG[0] + (col[0] - BG[0]) * a;
    var g0c = BG[1] + (col[1] - BG[1]) * a;
    var b0c = BG[2] + (col[2] - BG[2]) * a;
    for (var y2 = y0; y2 < y1; y2++) {
      var row2 = y2 * PW;
      for (var x2 = x0; x2 < x1; x2++) {
        var i2 = (row2 + x2) * 4;
        d[i2] = r0c; d[i2 + 1] = g0c; d[i2 + 2] = b0c;
      }
    }
  }

  function render() {
    var d = img.data;

    /* Заливка фоном удвоением строк, а не проходом по пикселям: на ретине это
       два с лишним миллиона точек, и посточечный цикл стоил три миллисекунды
       из шестнадцати с половиной. Здесь заполняется одна строка, а дальше
       буфер копирует сам себя, удваиваясь, — это уже перенос памяти. */
    var rowB = PW * 4;
    for (var x0 = 0; x0 < PW; x0++) {
      var i0 = x0 * 4;
      d[i0] = BG[0]; d[i0 + 1] = BG[1]; d[i0 + 2] = BG[2]; d[i0 + 3] = 255;
    }
    var done = 1;
    while (done < PH) {
      var take = done < PH - done ? done : PH - done;
      d.copyWithin(done * rowB, 0, take * rowB);
      done += take;
    }

    /* На касании поле жёстко привязано к экрану. Инерционная прокрутка на iOS
       выдаёт положение рывками, и поле, привязанное к бумаге, дрожит вместе с
       ней. У образца сделано ровно так же и по той же причине. */
    var sy = TOUCH ? 0 : scrollY * dpr;
    var off = sy - Math.floor(sy / step) * step;
    var r0 = Math.floor(sy / step) - 1;

    var floorY = measure.bottom;
    /* Затухание берёт разгон незадолго до низа первого экрана и заканчивается
       вскоре после него: песок не упирается в границу следующей секции, но и
       не тает раньше времени. В долях от высоты окна (0.34) разгон выходил в
       триста пикселей и съедал поле уже от кнопок, поэтому здесь пикселы. */
    var fadeFrom = floorY - 150, fadeTo = floorY + 90;
    var intro = reduce ? 1 : Math.min(1, t / INTRO);
    var wind = reduce ? 0 : t * DRIFT;

    /* Направление гребней поворачивается целиком, поэтому синус и косинус
       считаются раз на кадр, а не на каждую из сорока тысяч ячеек. */
    var ang = 0.55 + fsin(t * RIP_TURN) * 0.35;
    var rcos = fcos(ang), rsin = fsin(ang);


    /* Масштаб узора привязан к постоянной высоте, а не к высоте окна: делённый
       на PH, он растягивался вместе с ним — на ноутбуке в 900 точек узор
       выходил в четверть крупнее, чем на 720, и «тот же самый» песок на разных
       экранах выглядел разным.

       Закон считается на сетке ВТРОЕ реже ячеек, а между узлами растягивается.
       И гребень, и подложка меняются плавно: на трёх ячейках фаза уходит на
       0.13 радиана, и ошибка растяжки — меньше трети процента. Зато шума
       считается в девять раз меньше, и плотность можно держать высокой, не
       выходя за бюджет кадра. */
    var gc = Math.ceil(cols / LOD) + 2, gr = Math.ceil(rows / LOD) + 3;
    if (!grid || grid.length < gc * gr) grid = new Float32Array(gc * gr);
    for (var gy = 0; gy < gr; gy++) {
      var gdr = r0 + (gy - 1) * LOD;
      var gny = (gdr * step) / REF;
      for (var gx = 0; gx < gc; gx++) {
        var gnx = (gx * LOD * step) / REF;
        var gk = (gnx * SCALE * rcos + gny * SCALE * rsin) * 1.05
               + base(gnx * 0.8, gny * 0.8, t * 0.05) * RIP_WARP + t * RIP_RUN;
        var gband = 0.5 + 0.5 * fsin(gk * RIP_K);
        var gsoft = base(gnx * SCALE * 1.3 + wind, gny * SCALE * 1.3, t * 0.14);
        grid[gy * gc + gx] = gband * RIP_MIX + gsoft * (1 - RIP_MIX);
      }
    }

    var Rd = rad * dpr;
    var HOLE = Rd * CORE, BERM = HOLE * GROW;
    var SQZ = 1 - (HOLE * HOLE) / (BERM * BERM);     /* доля площади, что остаётся кольцу */
    var live = over && Rd > 1;

    /* Система хода: единичный вектор скорости и вытянутость по ней. Пока мышь
       почти стоит, вытягивания нет вовсе — иначе на остановке борозда схлопнется
       рывком. */
    /* Отставание песка от бумаги. Ограничено, иначе быстрый мах колесом
       превращает поле в смаз. */
    var slag = svel * SLAG * dpr;
    var slagMax = SLAG_MAX * dpr;
    if (slag > slagMax) slag = slagMax; else if (slag < -slagMax) slag = -slagMax;

    /* vy здесь — скорость мыши, модульная. Пока строка ячеек звалась тем же
       именем, её объявление внутри цикла поднималось сюда и обнуляло расчёт. */
    var vlen = Math.sqrt(vx * vx + vy * vy);
    var spd = Math.min(1, vlen / (VREF * dpr));
    var anis = spd > 0.06;
    var ux0 = anis ? vx / vlen : 1, uy0 = anis ? vy / vlen : 0;
    var ux = ux0, uy = uy0;
    var elong = 1 + spd * (ELONG - 1);

    for (var rr = 0; rr <= rows; rr++) {
      var dr = r0 + rr;
      var vr = rr - 1;                             /* строка на экране */
      var depth = dr * step;
      var ny = depth / PH;
      var cy = vr * step + sq * 0.5;                 /* середина ячейки на экране */
      var hid = (vr < 0 ? 0 : vr >= rows ? rows - 1 : vr) * cols;

      /* какие две строки редкой сетки обслуживают эту строку ячеек */
      var fy2 = (rr + LOD - 1) / LOD, gy0 = fy2 | 0, ty = fy2 - gy0;
      if (gy0 > gr - 2) { gy0 = gr - 2; ty = 1; }
      var gyBase = gy0 * gc, gyNext = (gy0 + 1) * gc;

      for (var c = 0; c < cols; c++) {
        /* Поле ровное сверху донизу. До этого густота росла книзу от 0.55,
           и у заголовка выживала едва половина крупинок: гребни проедались,
           а вместо сплошных полос оставались редкие штрихи — узор пропадал
           ровно там, куда смотрят. Текст держится не разрежением, а
           обтеканием боксов, и разрежение было лишним. */
        if (hash(c * 1.7 + 11.3, dr * 1.3 + 5.1) >= DENS) continue;
        if (hash(c * 2.3 + 7.1, dr * 1.9 + 3.3) >= intro) continue;

        /* рваное затухание ниже первого экрана */
        var wob = (fsin(c * 0.5 + SEED) + fsin(c * 0.21 - SEED * 1.3)) * 0.16
                + hash((c / 2) | 0, (dr / 4) | 0) * 0.6;
        var thr = depth <= fadeFrom ? 0
                : Math.min(1, (depth - fadeFrom) / (fadeTo - fadeFrom) - wob * 0.22);
        if (thr > 0 && hash(c * 0.7 + 4.4, dr * 0.9 + 1.1) >= 1 - thr) continue;

        /* Значение берётся из редкой сетки и растягивается по обеим осям */
        var fx2 = c / LOD, gx0 = fx2 | 0, tx = fx2 - gx0;
        var g00 = grid[gyBase + gx0], g10 = grid[gyBase + gx0 + 1];
        var g01 = grid[gyNext + gx0], g11 = grid[gyNext + gx0 + 1];
        var top = g00 + (g10 - g00) * tx, bot = g01 + (g11 - g01) * tx;

        var v = 0.5 + (top + (bot - top) * ty - 0.5) * CALM
              + (hash(c, dr) - 0.5) * 0.12;
        if (v < CUT) continue;

        /* Проявление у порога, сглаженное: у самой границы прибавка идёт
           медленно, поэтому появление крупинки не заметно вовсе. */
        var alpha = 1;
        if (v < CUT + SOFT) {
          var q = (v - CUT) / SOFT;
          alpha = q * q * (3 - 2 * q);
          if (alpha < 0.03) continue;
        }

        /* Ореол вокруг текста.

           Расстояние берётся обычное, круговое. Раньше бралась НАИБОЛЬШАЯ из
           двух сторон — а это прямоугольник, и его форму было видно: песок
           обрывался ровной рамкой, по которой читался сам текстовый блок.

           И гасится не только вероятность, но и яркость: у самого текста
           крупинок и меньше, и они бледнее. Одной вероятности мало — на
           границе всё равно остаётся ступенька плотности. */
        var cx = c * step + sq * 0.5;
        var skip = 0, halo = 1;
        for (var b = 0; b < boxes.length; b++) {
          var z = boxes[b];
          var bx = Math.max(z[0] - cx, cx - z[2], 0);
          var by = Math.max(z[1] - depth, depth - z[3], 0);
          var bd = Math.sqrt(bx * bx + by * by), pad = step * 20;
          if (bd > pad) continue;
          var pp = bd / pad, sm = pp * pp * (3 - 2 * pp);
          if (hash(c + 9.1, dr + 4.7) > sm) { skip = 1; break; }
          if (sm < halo) halo = sm;
        }
        if (skip) continue;
        alpha *= halo;
        if (alpha < 0.03) continue;

        var px = c * step, py = vr * step;

        /* У каждой крупинки своё отставание: с общим на всех поле ехало бы
           единой пластиной, а сыпучее тело так не ездит. */
        if (slag) py += slag * (0.35 + hash(c * 0.7, dr * 1.9) * 0.85);

        /* --- курсор раздвигает песок --------------------------------------
           Стоящая мышь оставляет круглое место, ведомая — борозду: область
           влияния вытягивается вдоль хода, а песок расталкивается не наружу
           от точки, а В СТОРОНЫ от линии хода. Так и работает рука, ведомая
           по песку: перед ней ничего не растёт, валы ложатся по бокам. */
        if (live) {
          var dx = cx - mx, dy = cy - my;

          /* расстояние в системе хода: вдоль — сжато, поперёк — как есть */
          var along = dx * ux + dy * uy;
          var acr = dx * uy0 - dy * ux0;
          var dd = anis
            ? Math.sqrt((along / elong) * (along / elong) + acr * acr)
            : Math.sqrt(dx * dx + dy * dy);

          /* Кромку рвём по крупинке. Без этого граница выходит циркулем, и
             песок читается вырезанным кружком, а не расступившимся. */
          dd += (hash(c * 0.9, dr * 1.1) - 0.5) * step * 3.4;

          if (dd < BERM) {
            /* ПЕРЕНОС С СОХРАНЕНИЕМ ВЕЩЕСТВА.

               Не удаляется ни одна крупинка. Круг радиуса HOLE выдавливает
               всё своё содержимое в кольцо до BERM, и перенос подобран так,
               чтобы площадь сходилась:

                   r' = sqrt(HOLE² + r² * (BERM² - HOLE²) / BERM²)

               Проверка по краям: ноль уходит ровно на HOLE, а BERM остаётся
               на месте, так что за кольцом поле не шелохнётся. Внутри кольца
               площадь сжимается в постоянное число раз — BERM²/(BERM²-HOLE²),
               то есть в 1.7 при нынешних числах, — и ровно во столько же раз
               там гуще песок. Вал берётся из счёта, а не из подкрутки. */
            if (dd < 0) dd = 0;
            var rp = Math.sqrt(HOLE * HOLE + dd * dd * SQZ);
            var move = rp - dd;
            var k = 1 - dd / BERM;                   /* 1 в середине, 0 у кромки */

            /* Направление выброса: на месте — прочь от точки, на ходу — вбок
               от линии. Смешиваются по скорости, поэтому переход незаметен. */
            var rl = Math.sqrt(dx * dx + dy * dy) || 1;
            var rxn = dx / rl, ryn = dy / rl;
            var sgn = acr >= 0 ? 1 : -1;
            var axn = uy0 * sgn, ayn = -ux0 * sgn;
            var mixk = anis ? spd * LATERAL : 0;
            var ox = rxn * (1 - mixk) + axn * mixk;
            var oy = ryn * (1 - mixk) + ayn * mixk;
            var ol = Math.sqrt(ox * ox + oy * oy) || 1;

            /* Разброс ПОПЕРЁК выброса.

               Без него крупинка, стоящая на одной высоте с курсором, едет
               строго вбок: смещение по второй оси у неё ровно ноль, и вся
               строка остаётся на одной прямой. Выброс её вдобавок поджимает,
               крупинки смыкаются вплотную — и от круга во все четыре стороны
               отрастают сплошные чёрточки. Вне осей этого нет: там крупинки
               расходятся по обеим осям сразу и слипнуться не успевают.

               Отклоняем каждую на своё, до полутора клеток, и линии больше
               не из чего сложиться. Разброс растёт вместе с выбросом, так что
               у кромки, где выброса почти нет, ничего не дрожит. */
            var sxn = -(oy / ol), syn = ox / ol;
            var jt = (hash(c * 4.1, dr * 6.3) - 0.5) * k * step * 3;

            px += (ox / ol) * move + sxn * jt;
            py += (oy / ol) * move + syn * jt;

            /* Слой у вала толще, а толстый песок темнее. Прибавка небольшая:
               основную работу делает сама плотность крупинок. */
            v += k * 0.18;
          }
        }

        /* --- след ---------------------------------------------------------- */
        var cvv = carve[hid + c];
        if (cvv > 0.02 && hash(c * 5.1, dr * 3.7) < cvv) continue;

        grain(d, px, py, SAND.tone(v), alpha);
      }
    }

    ctx.putImageData(img, 0, -off | 0);
  }

  /* Отпечаток следа: круг ячеек, которые ещё какое-то время остаются пустыми */
  function stamp(x, y, rr) {
    var cc = x / step, ccr = y / step;
    for (var dy2 = -rr; dy2 <= rr; dy2++) {
      for (var dx2 = -rr; dx2 <= rr; dx2++) {
        var c2 = (cc + dx2) | 0, r2 = (ccr + dy2) | 0;
        if (c2 < 0 || r2 < 0 || c2 >= cols || r2 >= rows) continue;
        var q = Math.sqrt(dx2 * dx2 + dy2 * dy2) / rr;
        if (q > 1) continue;
        var val = (1 - q) * 0.9;
        var id = r2 * cols + c2;
        if (val > carve[id]) carve[id] = val;
      }
    }
  }

  function frame(now) {
    if (!t0) t0 = now || 0;
    t = ((now || 0) - t0) / 1000;

    /* радиус разъезжается плавно: резкое появление круга при вводе курсора в
       окно выглядело бы щелчком */
    rad += (radT - rad) * 0.18;

    /* Скорость прокрутки — по тому же правилу, что и скорость мыши: по кадру,
       а не по событию. Событий прокрутки браузер выдаёт как придётся. */
    var syNow = scrollY;
    svel += ((syNow - sy0) - svel) * 0.4;
    sy0 = syNow;
    if (svel > 90) svel = 90; else if (svel < -90) svel = -90;

    /* Скорость считаем по кадру, а не по событию: событий мыши бывает и триста
       в секунду, и двадцать, а кадр один. Сглаживание убирает дрожь. */
    if (over && lx > -1e4) {
      vx += ((mx - lx) - vx) * 0.35;
      vy += ((my - ly) - vy) * 0.35;
    } else { vx *= 0.8; vy *= 0.8; }
    lx = mx; ly = my;

    /* след затягивается */
    for (var i = 0; i < carve.length; i++) {
      if (carve[i] > 0.001) carve[i] *= HEAL; else carve[i] = 0;
    }

    /* След ставится ПО ОТРЕЗКУ хода, а не в одной точке. На быстром взмахе
       событий приходит мало, и точечные отпечатки ложились бы пунктиром. */
    if (over && rad > 1) {
      var rr = Math.ceil((rad * dpr * CORE * 1.25) / step);
      for (var si = 0; si < seg.length; si++) {
        var sg = seg[si];
        var dlen = Math.hypot(sg[2] - sg[0], sg[3] - sg[1]);
        var nsteps = Math.min(24, 1 + Math.floor(dlen / (step * 1.5)));
        for (var q2 = 0; q2 < nsteps; q2++) {
          var tq = nsteps === 1 ? 1 : q2 / (nsteps - 1);
          stamp(sg[0] + (sg[2] - sg[0]) * tq, sg[1] + (sg[3] - sg[1]) * tq, rr);
        }
      }
      stamp(mx, my, rr);
    }
    seg.length = 0;

    render();
    if (!reduce) raf = requestAnimationFrame(frame);
  }

  function go() {
    if (!size()) { if (tries++ < 180) setTimeout(go, 32); return; }
    tries = 0; t0 = 0; t = 0;
    if (reduce) { t = INTRO; render(); } else frame(0);
  }
  go();

  /* Шрифт приезжает позже разметки, и заголовок после его подстановки меняет
     размеры. Боксы, снятые до этого, оставили бы песок лежать на буквах. */
  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(function () { if (cols) measure(); });
  }

  /* --- курсор --------------------------------------------------------------
     Холст мышь не ловит (pointer-events:none), поэтому слушаем окно. ------- */
  addEventListener('pointermove', function (e) {
    var hb = hero.getBoundingClientRect();
    var was = over;
    over = e.clientY < hb.bottom + 120;
    radT = over ? R : 0;
    var nx2 = e.clientX * dpr, ny2 = e.clientY * dpr;
    if (was && over && mx > -1e4) seg.push([mx, my, nx2, ny2]);
    mx = nx2; my = ny2;
    if (!was) { lx = mx; ly = my; vx = 0; vy = 0; }
  }, { passive: true });

  addEventListener('pointerleave', function () { over = false; radT = 0; }, { passive: true });

  /* На касании ухода курсора не бывает — палец просто отрывают. Без этого
     радиус остался бы раскрытым навсегда и порывы больше не завелись бы. */
  function lift() { if (TOUCH) { over = false; radT = 0; lx = -1e5; } }
  addEventListener('pointerup', lift, { passive: true });
  addEventListener('pointercancel', lift, { passive: true });

  /* Слушателя прокрутки здесь нет намеренно. Боксы записаны в координатах
     страницы и от прокрутки не зависят вовсе — пересчитывать их на каждое
     событие было бы чистой тратой. Скорость прокрутки читается в кадре. */

  /* Порыв не должен уходить в холостую, пока вкладку не смотрят: браузер и так
     останавливает кадры, но покой копился бы и по возвращении ветер дул бы
     сразу. */

  var timer = null, was = 0;
  addEventListener('resize', function () {
    if (innerWidth === was) return; was = innerWidth;
    clearTimeout(timer);
    timer = setTimeout(function () { cancelAnimationFrame(raf); raf = 0; go(); }, 180);
  });
})();
