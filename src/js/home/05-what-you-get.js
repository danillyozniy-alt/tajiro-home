/* ==========================================================================
   Сборка ниши — история с началом, а не бегущая строка. Если проиграть её
   в пустой экран, человек долистает до готовой арки и не увидит, из чего
   она сложилась. Поэтому весь механизм ставится на нулевой кадр и
   отпускается ровно тогда, когда фигура въехала в кадр.

   Одноразово: сработало — наблюдатель отключился, дальше секция живёт
   своим 24-секундным циклом, как 06–09. Прокрутка вверх ничего не
   переигрывает.
   ========================================================================== */
(function () {
  'use strict';

  var fig = document.getElementById('s05-figure');
  if (!fig || !('IntersectionObserver' in window)) return;

  /* При «меньше движения» останавливать нечего: в reduced-motion блоке
     CSS у фигуры нет ни одной анимации — только собранный кадр. */
  if (window.matchMedia &&
      window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;

  /* Фигура уже в кадре на загрузке — не трогаем вовсе. Пауза на видимом
     элементе читалась бы как подвисшая страница. Замер делаем здесь же,
     по ходу разбора документа: раскладка выше по странице уже готова,
     а классов появления (00-reveal.css) ещё нет — они ничего не сдвинут. */
  if (fig.getBoundingClientRect().top < (window.innerHeight || 0)) return;

  fig.classList.add('is-armed');

  /* Полоса наблюдения растянута вверх на всю страницу — тот же приём, что
     в js/reveal.js. С обычным rootMargin фигуру можно проскочить рывком
     (якорь из меню, бросок скролла) между двумя пересчётами наблюдателя:
     снизу ещё не пересекала, сверху уже не пересекает, коллбэка нет —
     и механизм остался бы на паузе навсегда. Растянутая полоса делает
     условие односторонним: «верх фигуры опустился ниже линии». */
  var band = Math.max(document.documentElement.scrollHeight, 10000);

  new IntersectionObserver(function (entries, obs) {
    if (!entries[0].isIntersecting) return;
    fig.classList.remove('is-armed');
    obs.disconnect();
  }, { rootMargin: band + 'px 0px -18% 0px', threshold: 0 }).observe(fig);
})();

