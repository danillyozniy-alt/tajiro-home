/* ==========================================================================
   tajiro — появление блоков при прокрутке
   Пара к css/00-reveal.css.

   Договор со стилями: пока на <html> нет класса .reveal-armed, ни одно
   правило из 00-reveal.css не срабатывает. Значит, порядок обязан быть
   именно такой:
     1) померить, что уже в кадре, — по нетронутой раскладке;
     2) снять крючки с того, что в кадре (ему появляться нечего);
     3) только теперь взвести .reveal-armed;
     4) подписать наблюдателя на остальное.
   Любая перестановка даёт вспышку: блок успевает мигнуть невидимым.

   Наблюдатель одноразовый: unobserve сразу по срабатыванию. Прокрутка
   вверх ничего не переигрывает — блок появляется ровно один раз за визит.
   ========================================================================== */
(function () {
  'use strict';

  var root = document.documentElement;

  /* .reveal — один блок целиком (интро секции).
     .reveal-set — контейнер сетки равных: наблюдаем ОДИН контейнер,
     а лесенку по детям раскладывает CSS. Один наблюдаемый узел на
     сетку вместо шести. */
  var targets = Array.prototype.slice.call(
    document.querySelectorAll('.reveal, .reveal-set')
  );
  if (!targets.length) return;

  /* Движение выключено — не взводим вообще. Это надёжнее, чем гасить
     анимацию: если систему взвести, а прокрутка до блока не дойдёт,
     он так и останется на opacity: 0 (в 00-base.css анимация сжата до
     0.01ms, но исходное состояние никуда не девается). В 00-reveal.css
     на этот же случай лежит страховочный медиа-блок. */
  var motionOff = window.matchMedia &&
                  window.matchMedia('(prefers-reduced-motion: reduce)');
  if (motionOff && motionOff.matches) return;

  /* Нет IntersectionObserver — оставляем страницу как есть. Скролл-обработчик
     как запасной путь не нужен: без него страница не хуже, а полностью
     нормальна. */
  if (!('IntersectionObserver' in window)) return;

  /* Линия срабатывания: верх блока пересёк 88 % высоты окна. Заведена
     через rootMargin, а не через threshold, чтобы правило не зависело от
     высоты элемента: панель в 1200 px и шапка в 90 px приезжают одинаково.
     С threshold: 0.2 высокая панель ждала бы 240 px своей высоты, а
     короткая шапка — 18 px, и секции просыпались бы вразнобой. */
  var TRIGGER = 0.88;

  /* Верхний край области наблюдения поднят выше документа целиком.
     Зачем: с обычным rootMargin '0px 0px -12% 0px' блок «пересекает»
     область только пока он в кадре. Если до него доехали рывком —
     якорь из меню, бросок скролла, перетаскивание ползунка, — он успевает
     проскочить снизу вверх между двумя пересчётами наблюдателя: снизу
     ещё не пересекал, сверху уже не пересекает, коллбэка нет вовсе,
     и блок остаётся невидимым навсегда. Растянутая вверх полоса делает
     условие односторонним: «верх блока опустился ниже линии» — и уже
     никогда не перестаёт быть истиной. Отсюда же следует, что обратно
     наверх ничего не переигрывается: выхода из области просто нет. */
  var TOP_BAND = Math.max(root.scrollHeight, 10000);
  /* Нижний отступ считается из TRIGGER, а не пишется числом: замер «что уже
     в кадре» на шаге 1 и линия наблюдателя обязаны быть одной и той же
     линией, иначе часть блоков попадёт в зазор между ними. */
  var ROOT_MARGIN = TOP_BAND + 'px 0px ' + ((TRIGGER - 1) * 100).toFixed(2) + '% 0px';

  /* Сколько живёт разметка появления. Читаем из CSS, чтобы значения
     не разъезжались: длительность + самый длинный хвост лесенки (5 шагов)
     + запас на кадр. */
  function msOf(name, fallback) {
    var raw = getComputedStyle(root).getPropertyValue(name).trim();
    if (!raw) return fallback;
    var n = parseFloat(raw);
    if (isNaN(n)) return fallback;
    return raw.slice(-2) === 'ms' ? n : n * 1000;
  }

  var LIFETIME = msOf('--reveal-dur', 500) + msOf('--reveal-step', 125) * 5 + 120;

  /* Появление и уборка за собой. Классы снимаются целиком: после этого
     элемент не совпадает ни с одним селектором 00-reveal.css, то есть
     у него не остаётся ни opacity, ни translate, ни — что важнее —
     блока-контейнера и контекста наложения для абсолютных потомков.
     Секции 03, 04, 06, 07, 08 держат внутри абсолютные слои; на самих
     помеченных контейнерах таких потомков нет, но убирать за собой
     всё равно правильно.

     setTimeout, а не animationend: срабатывает детерминированно даже
     если вкладка ушла в фон и анимации встали. Опоздание безвредно —
     до уборки блок уже виден (fill-mode: forwards). */
  function reveal(el) {
    el.classList.add('is-revealed');
    window.setTimeout(function () {
      el.classList.remove('is-revealed', 'reveal', 'reveal-set');
    }, LIFETIME);
  }

  /* --- 1–2. Замер по нетронутой раскладке ---------------------------------
     Всё, что на загрузке уже выше линии срабатывания, теряет крючки
     насовсем: такой блок не должен ни прятаться, ни появляться — он
     просто есть. Так закрывается требование «над сгибом — без вспышки».
     Считаем ДО добавления .reveal-armed, пока страница в исходном виде. */
  var vh = window.innerHeight || root.clientHeight;
  var pending = [];

  targets.forEach(function (el) {
    if (el.getBoundingClientRect().top < vh * TRIGGER) {
      el.classList.remove('reveal', 'reveal-set');
    } else {
      pending.push(el);
    }
  });

  /* --- 3. Взвод ------------------------------------------------------------ */
  root.classList.add('reveal-armed');
  if (!pending.length) return;

  /* --- 4. Наблюдение ------------------------------------------------------- */
  var io = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (!entry.isIntersecting) return;
      io.unobserve(entry.target);   /* один раз — и больше никогда */
      reveal(entry.target);
    });
  }, { root: null, rootMargin: ROOT_MARGIN, threshold: 0 });

  pending.forEach(function (el) { io.observe(el); });
})();
