/* ==========================================================================
   tajiro — ссылки шапки и подвала на внутренней странице

   Шапка и подвал — один партиал на весь сайт, и это правильно: одинаковое
   меню на всех страницах и есть признак одного сайта. Но ссылки в них
   якорные, а секции, на которые они ведут, живут на домашней странице.
   На «Start for Free» половины этих секций нет, и нажатие не делало бы
   ничего вовсе — молча, что хуже любой ошибки.

   Здесь такие ссылки переписываются в межстраничные: #the-math становится
   index.html#the-math. Домашней страницы это не касается — там все секции
   на месте, скрипт к ней не подключён, и партиал остаётся один.

   Проверяется наличие цели в документе, а не имя страницы: добавится сюда
   секция — ссылка на неё сама снова станет якорной, ничего не правя.
   ========================================================================== */
(function () {
  'use strict';

  /* Секции домашней страницы. Список нужен, чтобы не трогать заглушки вроде
     #start и #contact: настоящей цели у них пока нет нигде, и отправлять
     человека за ней на другую страницу — значит менять пустое нажатие на
     пустую перезагрузку. */
  var HOME = [
    'hero', 'stats', 'ai-influencers', 'how-it-works', 'what-you-get',
    'pillar-store', 'pillar-products', 'pillar-marketing', 'social-proof',
    'the-math', 'personal-manager', 'trust-security', 'footer-cta'
  ];

  var links = document.querySelectorAll('a[href^="#"], a[href="free-store.html"]');

  Array.prototype.forEach.call(links, function (a) {
    var href = a.getAttribute('href');

    /* Кнопка «Start for Free» ведёт на эту самую страницу — мы уже здесь.
       Перезагружать её ради прокрутки наверх незачем, поэтому ссылка
       становится тем же местом, куда ведут кнопки самой страницы. */
    if (href === 'free-store.html') { a.setAttribute('href', '#start'); return; }

    var id = href.slice(1);
    if (!id || document.getElementById(id)) return;
    if (HOME.indexOf(id) < 0) return;

    a.setAttribute('href', 'index.html#' + id);
  });
})();
