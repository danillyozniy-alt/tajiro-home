
/* ==========================================================================
   tajiro — течение на первом экране
   Пара к блоку «Течение» в css/01-hero.css.

   ПЕРЕНЕСЕНО ИЗ ВАРИАНТА B с тремя правками:

     · фон берётся из стилей, а не константой. Там полотно лежало на
       кремовом, здесь — на бежевом, и зашитый цвет проступал бы рамкой
       по краям секции;
     · линии заметнее примерно в полтора раза: в прежнем виде течение
       угадывалось только на хорошем экране;
     · тёплое пятно тоже чуть плотнее и гаснет в прозрачность, а не в
       кремовый, — иначе оно тянуло цвет полотна к чужому.

   Полотно из текучих линий во всю ширину экрана, за текстом. Приём взят
   с первого экрана экомзи: там такие же волны на канвасе, только в
   неоне на чёрном. У нас палитра своя — песок и золото на бежевом, — и
   на ней те же линии читаются рябью по песку или нитями в ткани, а не
   подсветкой серверной. Зелёный из ленты убран: он на этом экране
   работает акцентом, и размазывать его по фону нельзя.

   ПОЧЕМУ КАНВАС, А НЕ CSS

   Линий полсотни, каждая гнётся по трём синусоидам с разной фазой и
   перекрашивается по ходу. На CSS это либо пятьдесят элементов с
   бесконечными анимациями, либо SVG-фильтры — и то и другое дороже, и
   ни то ни другое не даёт непрерывной волны, только петлю.

   ЧТО РИСУЕТСЯ

   Каждая линия — синус, сложенный из трёх волн: несущая, длинная и
   мелкая рябь. Амплитуда растёт к краям полотна и гаснет к середине,
   поэтому в центре, где стоит текст, всегда спокойнее.

   Цвет берётся из ленты песок → золото → зелёный по положению линии,
   и лента медленно ползёт: полотно перекрашивается само.

   ЦЕНА КАДРА

   Пятьдесят обводок по сто двадцать точек. Считается один раз за кадр,
   ничего не выделяется в цикле. За экраном отрисовка останавливается
   наблюдателем: невидимое полотно не должно жечь батарею.
   ========================================================================== */
(function () {
  'use strict';

  var canvas = document.getElementById('hero-flow');
  if (!canvas || !canvas.getContext) return;

  var ctx = canvas.getContext('2d');
  if (!ctx) return;

  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)');

  /* --- Настройки ---------------------------------------------------------- */

  var LINES   = 46;      /* больше — полотно превращается в заливку */
  var SPACING = 8.5;     /* расхождение линий по вертикали */
  var STEPS   = 120;     /* точек на линию */
  var SPEED   = 0.0034;  /* прирост времени за кадр */

  /* Подложку холст не рисует вовсе: он лежит на секции, у которой свой
     цвет, и достаточно очищаться в прозрачность.

     В варианте B здесь была заливка кремовым константой. Повторять это
     нельзя: полотно у нас бежевое, и зашитый цвет проступал бы каймой.
     Брать цвет у родителя тоже нельзя — у .s-hero__flow фона нет, и
     заливка получалась прозрачной, то есть холст не затирался вовсе, а
     кадры копились друг на друге и слипались в цветную кашу. */

  /* Лента цвета: песок → золото → песок. Замкнута намеренно, иначе на
     стыке полотно резко перекрашивается.

     Зелёного в ленте нет. В варианте B он был — две ступени из шести, — но
     на первом экране зелёный работает акцентом: кнопка, курсив в
     заголовке, точка в логотипе. Тот же цвет, размазанный по фону, эти
     акценты обесценивает. Осталась одна тёплая гамма, и течение читается
     песком, а не подсветкой. */
  var PALETTE = [
    [212, 163, 115],
    [196, 145,  92],
    [172, 120,  62],
    [150, 102,  47],
    [176, 136,  92],
    [203, 170, 131],
    [212, 163, 115]
  ];

  /* --- Служебное ---------------------------------------------------------- */

  var w = 0, h = 0, dpr = 1, t = 0, raf = 0;

  function resize() {
    var box = canvas.parentElement.getBoundingClientRect();
    if (!box.width || !box.height) return false;

    dpr = Math.min(window.devicePixelRatio || 1, 2);
    w = box.width;
    h = box.height;
    canvas.width  = Math.round(w * dpr);
    canvas.height = Math.round(h * dpr);
    canvas.style.width  = w + 'px';
    canvas.style.height = h + 'px';
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    return true;
  }

  function mix(a, b, k) {
    return [
      a[0] + (b[0] - a[0]) * k,
      a[1] + (b[1] - a[1]) * k,
      a[2] + (b[2] - a[2]) * k
    ];
  }

  function colour(p) {
    p = p - Math.floor(p);                    /* лента замкнута */
    var last = PALETTE.length - 1;
    var i = Math.floor(p * last);
    if (i >= last) return PALETTE[last];
    return mix(PALETTE[i], PALETTE[i + 1], p * last - i);
  }

  /* --- Кадр --------------------------------------------------------------- */

  function draw() {
    t += SPEED;

    ctx.clearRect(0, 0, w, h);

    var midY = h * 0.46;

    /* Размах волны. В варианте B было 0.26 — поле линий сидело узкой
       полосой посередине и не доставало ни до верха, ни до низа полосы.
       Вместе с увеличенным SPACING течение теперь занимает экран по всей
       высоте. Что вылезло за кромку, срезается overflow у .s-hero__flow. */
    var amp  = h * 0.44;

    for (var i = 0; i < LINES; i++) {
      var r    = i / (LINES - 1);            /* положение линии, 0…1 */
      var off  = (i - LINES / 2) * SPACING;
      var ph   = r * Math.PI * 1.2 + t * 0.6;

      /* Расстояние от середины полотна. В центре линии спокойнее и
         бледнее: там стоит текст, и рябь под ним мешала бы читать. */
      var edge = Math.abs(r - 0.5) * 2;
      var la   = amp * (0.42 + edge * 0.72);

      var c = colour(r * 0.8 + t * 0.03);
      /* Плотность подбиралась вилкой по живому экрану.

         Мерка — средняя альфа холста, из 255. В варианте B было 0.05 и
         0.13, альфа выходила 6.2 — течения не видно вовсе. На 0.15 и 0.30
         альфа поднималась до 13.6, и линии лезли вперёд. На 0.10 и 0.21
         выходило 9.3 — всё ещё многовато. Остановились на восьми.

         Просвечивание фигуры этим больше не задевается: её край уплотнён
         отдельно, кайма ужата с 4.6 % до 0.9 %. */
      var a = (0.086 + edge * 0.18) * (0.62 + Math.sin(t + r * 5) * 0.24);

      ctx.strokeStyle = 'rgba(' + (c[0] | 0) + ',' + (c[1] | 0) + ',' + (c[2] | 0) + ',' + a.toFixed(3) + ')';
      ctx.lineWidth = 1.1 + (1 - edge) * 0.45;
      ctx.beginPath();

      for (var s = 0; s <= STEPS; s++) {
        var k  = s / STEPS;
        var x  = k * (w + 200) - 100;
        var w1 = Math.sin(k * Math.PI * 2.5 + ph) * la;
        var w2 = Math.sin(k * Math.PI * 1.8 + ph * 0.7 + 1.5) * la * 0.4;
        var w3 = Math.sin(k * Math.PI * 4.2 + (t + r * 0.3) * 1.3) * la * 0.08;
        var en = Math.sin(k * Math.PI);       /* к краям экрана волна гаснет */
        var tw = Math.sin(k * Math.PI * 2 + t * 0.3) * off * 1.2;
        var y  = midY + (w1 + w2 + w3) * en + off * (0.8 + en * 0.6) + tw * en;

        if (s === 0) ctx.moveTo(x, y); else ctx.lineTo(x, y);
      }

      ctx.stroke();
    }

    /* Тёплое пятно, медленно гуляющее по полотну: без него поле линий
       читается ровным и потому механическим. */
    var gx = w * 0.5 + Math.sin(t * 0.5) * w * 0.1;
    var gy = midY + Math.cos(t * 0.3) * h * 0.06;
    var g  = ctx.createRadialGradient(gx, gy, 0, gx, gy, Math.max(w, h) * 0.42);
    g.addColorStop(0, 'rgba(212, 163, 115, 0.082)');
    g.addColorStop(0.45, 'rgba(150, 102, 47, 0.034)');
    g.addColorStop(1, 'rgba(212, 163, 115, 0)');
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, w, h);

    raf = requestAnimationFrame(draw);
  }

  /* Один кадр без движения: система просит покоя. Полотно остаётся, но
     не течёт — экран не становится пустым, а просто замирает. */
  function still() {
    cancelAnimationFrame(raf);
    raf = 0;
    t = 1.7;          /* фаза, на которой рисунок самый спокойный */
    var keep = SPEED;
    SPEED = 0;
    draw();
    cancelAnimationFrame(raf);
    raf = 0;
    SPEED = keep;
  }

  /* --- Запуск ------------------------------------------------------------- */

  /* Замер повторяется, пока коробка не появится.

     Одного замера не хватает: секция получает высоту только после того,
     как разложится текст и приедут шрифты, а до этого коробка нулевая и
     холст остаётся заглушкой 300×150. Ловить это событиями ненадёжно —
     их порядок разный в разных браузерах, — поэтому просто пробуем на
     каждом кадре, пока не выйдет, и не дольше двух секунд. */
  var tries = 0;

  function start() {
    if (!resize()) {
      /* Таймер, а не кадр: в скрытой или несведённой вкладке
         requestAnimationFrame не срабатывает вовсе, и повтор замера
         никогда не случится — холст останется заглушкой 300×150. */
      if (tries++ < 120) setTimeout(start, 32);
      return;
    }
    tries = 0;
    if (reduce && reduce.matches) { still(); return; }
    /* Рисуем сразу, а не ждём кадра: пока страница не показана,
       requestAnimationFrame не срабатывает вовсе, и полотно остаётся
       пустым. draw в конце сам заводит следующий кадр. */
    if (!raf) draw();
  }

  function stop() {
    cancelAnimationFrame(raf);
    raf = 0;
  }

  start();

  /* За экраном не рисуем: невидимое полотно жечь батарею не должно. */
  if (window.IntersectionObserver) {
    new IntersectionObserver(function (rows) {
      if (rows[0].isIntersecting) start(); else stop();
    }, { threshold: 0.04 }).observe(canvas.parentElement);
  }

  /* Пересборка на изменение ширины — с задержкой: тянуть окно можно долго,
     а каждый пересчёт заново заводит холст. */
  var timer = null, was = 0;
  window.addEventListener('resize', function () {
    var now = Math.round(canvas.parentElement.getBoundingClientRect().width);
    if (now === was) return;      /* высота адресной строки на телефоне
                                     меняется постоянно, ширина — нет */
    was = now;
    clearTimeout(timer);
    timer = setTimeout(function () { stop(); start(); }, 160);
  });

  if (reduce) {
    var onReduce = function () { stop(); start(); };
    if (reduce.addEventListener) reduce.addEventListener('change', onReduce);
    else if (reduce.addListener) reduce.addListener(onReduce);
  }

  /* Шрифты меняют высоту секции уже после первого кадра — пересобираем,
     иначе полотно окажется короче экрана. */
  window.addEventListener('load', function () { stop(); start(); });
})();
